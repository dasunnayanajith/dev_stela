                        <h2 class="blog-title">Cancellation Policy</h2>
                        <p class="blog-text mb-30">
                            <strong>Stelaran Holidays (Pvt) Ltd</strong> understands that travel plans may change. To ensure a smooth process for all our guests, the following cancellation policy applies to all confirmed tour bookings.
                        </p>

                        <h3 class="h4 mt-4">1. Cancellation by the Traveler</h3>
                        <p class="blog-text">If you cancel your booking, the following cancellation charges will apply based on the timeframe of the notification:</p>
                        <ul class="blog-text mb-30">
                            <li><strong>31 – 60 days before arrival:</strong> Deposit is non-refundable.</li>
                            <li><strong>15 – 30 days before arrival:</strong> 25% of the total tour cost will be charged.</li>
                            <li><strong>08 – 14 days before arrival:</strong> 50% of the total tour cost will be charged.</li>
                            <li><strong>07 days or less before arrival:</strong> 100% of the total tour cost will be charged.</li>
                        </ul>

                        <h3 class="h4 mt-4">2. Cancellation After Tour Commencement</h3>
                        <blockquote>
                            <p>Once the tour has started, no refunds will be provided for any unused services including accommodation, transportation, meals, or activities.</p>
                        </blockquote>

                        <h3 class="h4 mt-4">3. Supplier Cancellation Policies</h3>
                        <p class="blog-text">
                            Certain hotels, airlines, and activity providers may have stricter cancellation policies. In such cases, their specific conditions may apply in addition to our standard policy.
                        </p>

                        <h3 class="h4 mt-4">4. Cancellation Due to Unforeseen Circumstances</h3>
                        <p class="blog-text">
                            In cases such as natural disasters, government travel restrictions, or flight cancellations, Stelaran Holidays will assist in rescheduling the tour where possible. However, refunds will depend on the policies of third‑party service providers.
                        </p>

                        <h3 class="h4 mt-4">5. Cancellation by Stelaran Holidays</h3>
                        <p class="blog-text">
                            In rare circumstances where Stelaran Holidays must cancel a tour due to operational reasons or events beyond our control, we will offer an alternative arrangement or a refund of the amount paid for unused services where possible.
                        </p>

